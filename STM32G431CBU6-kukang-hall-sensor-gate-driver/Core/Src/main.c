void Check_PB8_BOOT0_Config(void) {
  FLASH_OBProgramInitTypeDef OBInit;
  HAL_FLASHEx_OBGetConfig(&OBInit);

  // If BOOT0 is currently taken from PIN (FLASH_OPTR_nSWBOOT0 is set),
  // we must change it to OB_BOOT0_FROM_OB and ensure nBOOT0 = 1 so PB8 is freed
  // for CAN RX!
  if ((OBInit.USERConfig & FLASH_OPTR_nSWBOOT0) != 0) {
    HAL_FLASH_Unlock();
    HAL_FLASH_OB_Unlock();

    OBInit.OptionType = OPTIONBYTE_USER;
    OBInit.USERType = OB_USER_nSWBOOT0 | OB_USER_nBOOT0;
    OBInit.USERConfig = OB_BOOT0_FROM_OB | OB_nBOOT0_SET;

    if (HAL_FLASHEx_OBProgram(&OBInit) == HAL_OK) {
      HAL_FLASH_OB_Launch(); // Applies Option Bytes and resets MCU
    }
    HAL_FLASH_OB_Lock();
    HAL_FLASH_Lock();
  }
}

void HAL_FDCAN_RxFifo0Callback(FDCAN_HandleTypeDef *hfdcan,
                               uint32_t RxFifo0ITs) {
  if ((RxFifo0ITs & FDCAN_IT_RX_FIFO0_NEW_MESSAGE) != RESET) {
    if (HAL_FDCAN_GetRxMessage(hfdcan, FDCAN_RX_FIFO0, &RxHeader, RxData) ==
        HAL_OK) {
      if (RxHeader.Identifier == 0x10) {
        can_target_run_state = RxData[0];
        can_target_rpm = (uint16_t)(RxData[1] | (RxData[2] << 8));
        last_can_cmd_tick = HAL_GetTick();
        can_cmd_pending = 1;
      }
    }
  }
}

void Process_USB_Receive(uint8_t *Buf, uint32_t Len) {
  for (uint32_t i = 0; i < Len; i++) {
    if (usb_rx_index < sizeof(usb_rx_buffer) - 1) {
      usb_rx_buffer[usb_rx_index++] = Buf[i];
      if (Buf[i] == '\n' || Buf[i] == '\r') {
        usb_cmd_ready = 1;
      }
    } else {
      usb_rx_index = 0; // Overflow, reset
    }
  }
}

void Parse_USB_Command(void) {
  if (usb_cmd_ready) {
    for (int i = 0; i < usb_rx_index; i++) {
      if (usb_rx_buffer[i] == '\r' || usb_rx_buffer[i] == '\n') {
        usb_rx_buffer[i] = '\0';
        break;
      }
    }
    usb_rx_buffer[usb_rx_index] = '\0';

    Config_ParseCommand((char *)usb_rx_buffer);

    usb_rx_index = 0;
    usb_cmd_ready = 0;
  }
}
