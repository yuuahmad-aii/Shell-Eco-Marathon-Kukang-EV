  DWT->CYCCNT = 0;
  DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;

  uint32_t last_verbose_time = HAL_GetTick();
  uint32_t last_can_status_tick = HAL_GetTick();
  uint32_t last_cycle_count = DWT->CYCCNT;
